/* ------------------------------------------------------------------ *
 * Sport-specific full-layout templates (Choose a template gallery).
 * Every one ships the complete landing composition: wordmark + tagline,
 * hero photo slot, big headline, body, 4-icon feature strip, arrow CTA
 * and the members social-proof row — exactly like the reference sheet.
 * ------------------------------------------------------------------ */

type FullTemplateSpec = {
  id: string;
  label: string;
  vibe: string;
  wordmark: string;
  tagline: string;
  headline: string;
  body: string;
  cta: string;
  features: [string, string, string, string];
  icons?: [string, string, string, string];
  count: string;
  countLabel: string;
  extra: string;
  /** dark page bg */
  bg: string;
  bgVia: string;
  accent: string;
  accentHover: string;
  ctaBg: string;
  ctaTo?: string;
  ctaText: string;
  text: string;
  muted: string;
  radius?: number;
  light?: boolean;
  /** key in SPORT_PHOTOS */
  photo: string;
  /** script signature line rendered as its own layer */
  signature?: string;
  /** editable pill in the top nav */
  badge?: string;
  /** 2x2 card grid — title / subtitle / icon / destination page */
  cards?: [string, string][];
  tags: string[];
  /** Real athlete this reference template was designed for. */
  athlete?: string;
};

