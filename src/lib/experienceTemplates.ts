/** Apply a template's look on top of an existing experience config. */
export function applyExperienceTemplate(
  config: ExperienceConfig,
  template: ExperienceTemplate,
): ExperienceConfig {
  const ctaBg = template.theme.buttonBg;
  const ctaText = template.theme.buttonText;
  /** Every template loads its artwork into the preview — delete it there if unwanted. */
  const art = template.landing?.heroImage ?? template.photo;
  /** Full designed page set (home, social, videos, news, shop, profile…). */
  const templatePages = buildTemplatePages(template);
  const pages = Object.fromEntries(
    Object.entries(config.pages).map(([key, page]) => {
      /**
       * Templates replace, they never stack: builtin pages start from a clean
       * default so layers/art from a previously picked template are dropped
       * instead of sitting underneath the new look.
       */
      const base =
        (DEFAULT_EXPERIENCE_PAGES as Record<string, typeof page>)[key] ?? page;
      const clean = {
        ...base,
        stage: (base.stage ?? []).map((s) => ({ ...s })),
        features: (base.features ?? []).map((f) => ({ ...f })),
        memberProof: { ...base.memberProof },
      };
      let next = ctaBg && ctaText ? { ...clean, ctaBg, ctaText } : clean;
      const built = templatePages[key as keyof typeof templatePages];
      if (built) {
        next = {
          ...next,
          ...built,
          features: (built.features ?? next.features).map((f) => ({ ...f })),
          memberProof: { ...next.memberProof, ...(built.memberProof ?? {}) },
          stage: (built.stage ?? next.stage).map((s) => ({ ...s })),
        };
      }
      if (key === "landing") {
        if (template.landing) {
          next = {
            ...next,
            ...template.landing,
            features: (template.landing.features ?? next.features).map((f) => ({ ...f })),
            memberProof: { ...next.memberProof, ...(template.landing.memberProof ?? {}) },
            stage: (template.landing.stage ?? next.stage).map((s) => ({ ...s })),
          };
        }
        if (art) {
          next = {
            ...next,
            heroImage: art,
            heroFit: next.heroFit || "cover",
            // make sure the hero slot is visible so the art always lands in the preview
            stage: (next.stage ?? []).map((s) =>
              (s.id === "hero" || s.role === "hero") ? { ...s, hidden: false } : s,
            ),
          };
        }
      }
      return [key, next];
    }),
  ) as ExperienceConfig["pages"];

  const navTabs = TEMPLATE_NAV_TABS[template.id];

  return {
    ...config,
    brand: { ...config.brand, ...template.brand },
    theme: { ...config.theme, ...template.theme },
    effects: { ...config.effects, ...template.effects },
    nav: navTabs
      ? {
          ...config.nav,
          tabs: navTabs.map((t) => ({ ...t })),
          activeColor: template.theme.accent ?? config.nav.activeColor,
          bg: template.theme.bg ?? config.nav.bg,
        }
      : config.nav,
    pages,
  };
}



/** Best-guess of which template the current theme came from (accent match). */
export function detectExperienceTemplate(config: ExperienceConfig): string | null {
  const accent = config.theme.accent?.toUpperCase();
  return (
    EXPERIENCE_TEMPLATES.find((t) => t.theme.accent?.toUpperCase() === accent)?.id ?? null
  );
}
